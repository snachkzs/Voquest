const modal = document.getElementById('courseModal');
const modalTitle = document.getElementById('modalTitle');
const vocabList = document.getElementById('vocabList');
const docsList = document.getElementById('docsList');
const videoContainer = document.getElementById('videoContainer');
const closeBtn = document.querySelector('.close-modal');
const closeModalBtn = document.getElementById('closeModalBtn');

document.querySelectorAll('.course-card').forEach(card => {
  card.addEventListener('click', function() {
    const courseId = this.getAttribute('data-course');
    openModal(courseId);
  });
});

function openModal(courseId) {
  const course = courseData[courseId];
  if (!course) return;

  modalTitle.textContent = course.title;

  vocabList.innerHTML = '';
  course.vocabulary.forEach(item => {
    const vocabItem = document.createElement('div');
    vocabItem.className = 'vocab-item';
    vocabItem.innerHTML = `
      <div class="vocab-word">
        ${item.word}
        <span class="phonetic">${item.phonetic}</span>
      </div>
      <div class="vocab-meaning">${item.meaning}</div>
      <div class="vocab-example">"${item.example}"</div>
      <div class="vocab-usage"><strong>Usage:</strong> ${item.usage}</div>
    `;
    vocabList.appendChild(vocabItem);
  });

  docsList.innerHTML = `<div class="docs-text">${course.docs}</div>`;

  // Add YouTube video
  if (course.videoUrl && videoContainer) {
    videoContainer.innerHTML = `
      <iframe 
        width="100%" 
        height="400" 
        src="${course.videoUrl}" 
        title="YouTube video player" 
        frameborder="0" 
        allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" 
        allowfullscreen>
      </iframe>
    `;
  }

  modal.style.display = 'block';
  modal.classList.add('show');
  document.body.style.overflow = 'hidden';
}

function closeModal() {
  modal.style.display = 'none';
  modal.classList.remove('show');
  document.body.style.overflow = 'auto';
}

closeBtn?.addEventListener('click', closeModal);
closeModalBtn?.addEventListener('click', closeModal);

window.addEventListener('click', function(event) {
  if (event.target === modal) closeModal();
});

document.addEventListener('keydown', function(event) {
  if (event.key === 'Escape' && modal.style.display === 'block') closeModal();
});